// S2T converts Simplified Chinese to Traditional.
func S2T(text string) string {
	return convert(text, s2tMap)
}

// T2S converts Traditional Chinese to Simplified.
func T2S(text string) string {
	return convert(text, t2sMap)
}

// AutoConvert normalizes mixed text to Simplified (canonical form).
func AutoConvert(text string) string {
	return T2S(text)
}

func convert(text string, m map[rune]rune) string {
	var out []rune
	for _, r := range text {
		if tr, ok := m[r]; ok {
			out = append(out, tr)
		} else {
			out = append(out, r)
		}
	}
	return string(out)
}
