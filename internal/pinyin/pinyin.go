// ToPinyin converts a string to space-separated toneless pinyin.
// Characters without a known mapping are passed through as-is.
func ToPinyin(s string) string {
	var parts []string
	for _, r := range s {
		if py, ok := charPinyin[r]; ok {
			parts = append(parts, py)
		} else if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' {
			parts = append(parts, string(r))
		} else if r >= '0' && r <= '9' {
			parts = append(parts, string(r))
		}
	}
	return strings.Join(parts, " ")
}

// Of returns the pinyin for a single character, or empty string if unknown.
func Of(r rune) string {
	if py, ok := charPinyin[r]; ok {
		return py
	}
	return ""
}

// Has reports whether a character has a known pinyin mapping.
func Has(r rune) bool {
	_, ok := charPinyin[r]
	return ok
}
